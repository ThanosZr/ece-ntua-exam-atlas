window.pushExamSchedule = function(program, year, schedule){
  for(const day of schedule){
    const date = day[0];
    for(const slot of day.slice(1)){
      const time = slot[0];
      for(const item of slot.slice(1)){
        let source_title, note='';
        if(Array.isArray(item)){ source_title=item[0]; note=item[1]||''; }
        else source_title=item;
        const course = window.CANONICAL_ALIASES[source_title] || source_title;
        window.EXAM_ROWS.push({exam_type:program,source_year:year,date,time,course,source_title,note});
      }
    }
  }
};
